// DUAL-02: generate src/core/font-metrics.js from the bundled open fonts in public/fonts (fonts.lock.json).
// Reads each TTF's cmap (format 4 or 12), hmtx/hhea and head tables with a small bounded parser (no dependency) and
// records the advance width of every covered code point in the supported Unicode blocks, plus the file's SHA-256.
// The output is plain data, so the validator, the Director and both renderers share the same metrics.
// Usage: node scripts/font-metrics.mjs [--check]   (--check fails when the committed module is out of date)
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join,resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..'),lock=JSON.parse(readFileSync(join(root,'public','fonts','fonts.lock.json'),'utf8'));
// Supported blocks: Basic Latin, Latin-1, Latin Extended-A/B, Greek, Cyrillic, punctuation, super/subscripts,
// currency, letterlike symbols, arrows, mathematical operators.
export const BLOCKS=[[0x20,0x7e],[0xa0,0xff],[0x100,0x17f],[0x180,0x24f],[0x370,0x3ff],[0x400,0x4ff],[0x2000,0x206f],[0x2070,0x209f],[0x20a0,0x20cf],[0x2100,0x214f],[0x2190,0x21ff],[0x2200,0x22ff]];
function parse(buf){
 if(buf.length<12||buf.length>8e6)throw Error('font size out of bounds');
 const u16=o=>buf.readUInt16BE(o),u32=o=>buf.readUInt32BE(o),n=u16(4),tables={};
 if(![0x00010000,0x74727565].includes(u32(0))||n>64)throw Error('not a TrueType font');
 for(let i=0;i<n;i++){const r=12+16*i,tag=buf.toString('latin1',r,r+4),off=u32(r+8),len=u32(r+12);if(off+len>buf.length)throw Error('table out of bounds: '+tag);tables[tag]={off,len};}
 for(const t of ['head','hhea','hmtx','cmap','maxp'])if(!tables[t])throw Error('missing table '+t);
 const upem=u16(tables.head.off+18),nh=u16(tables.hhea.off+34),glyphs=u16(tables.maxp.off+4);
 const adv=g=>u16(tables.hmtx.off+4*Math.min(g,nh-1));
 // cmap: prefer (3,10) format 12, else (3,1)/(0,x) format 4
 const c=tables.cmap.off,subs=[];for(let i=0;i<u16(c+2);i++){const r=c+4+8*i;subs.push({p:u16(r),e:u16(r+2),off:c+u32(r+4)});}
 const pick=subs.find(s=>u16(s.off)===12&&(s.p===3&&s.e===10||s.p===0))??subs.find(s=>u16(s.off)===4&&(s.p===3&&s.e===1||s.p===0));
 if(!pick)throw Error('no usable cmap');
 const map=new Map(),o=pick.off;
 if(u16(o)===12){const groups=u32(o+12);if(groups>65536)throw Error('cmap too large');for(let i=0;i<groups;i++){const r=o+16+12*i,s=u32(r),e=u32(r+4),g=u32(r+8);for(let cp=s;cp<=e&&cp<=0x22ff;cp++)map.set(cp,g+cp-s);}}
 else{const seg=u16(o+6)/2,ends=o+14,starts=ends+2*seg+2,deltas=starts+2*seg,ranges=deltas+2*seg;
  for(let i=0;i<seg;i++){const e=u16(ends+2*i),s=u16(starts+2*i),d=u16(deltas+2*i),ro=u16(ranges+2*i);
   for(let cp=s;cp<=e&&cp!==0xffff;cp++){let g;if(ro===0)g=(cp+d)&0xffff;else{const a=ranges+2*i+ro+2*(cp-s);g=u16(a);if(g)g=(g+d)&0xffff;}if(g&&g<glyphs)map.set(cp,g);}}}
 return {upem,map,adv};
}
// Runs of consecutive covered code points: [start, width…] in 1/1000 em (rounded).
function runs(font){const out=[];let cur=null;
 for(const [a,b] of BLOCKS)for(let cp=a;cp<=b;cp++){const g=font.map.get(cp);if(g===undefined){cur=null;continue;}const w=Math.round(font.adv(g)*1000/font.upem);if(!cur){cur=[cp];out.push(cur);}cur.push(w);}
 return out;}
const fonts={};
for(const [id,f] of Object.entries(lock.fonts)){
 fonts[id]={family:f.family,css:f.css,licence:f.licence,source:f.source,faces:{}};
 for(const [weight,file] of Object.entries(f.files)){const buf=readFileSync(join(root,'public','fonts',file.path)),sha=createHash('sha256').update(buf).digest('hex');
  if(sha!==file.sha256)throw Error(file.path+': SHA-256 '+sha+' does not match fonts.lock.json');
  fonts[id].faces[weight]={path:'fonts/'+file.path,sha256:sha,runs:runs(parse(buf))};}
}
const text='// GENERATED by scripts/font-metrics.mjs from public/fonts/fonts.lock.json — do not edit by hand.\n'+
 '// Advance widths (1/1000 em) of covered code points as runs [start, width…]; SHA-256 of each source file.\n'+
 'export const FONT_METRICS='+JSON.stringify({version:1,fonts})+';\n';
const target=join(root,'src','core','font-metrics.js');
if(process.argv.includes('--check')){if(readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==text){console.error('font-metrics.js is out of date; run node scripts/font-metrics.mjs');process.exit(1);}console.log('font-metrics.js up to date');}
else{writeFileSync(target,text);console.log('wrote',target,Object.entries(fonts).map(([k,v])=>k+':'+Object.keys(v.faces).join('/')).join(' '));}
