// Re-render only the four historically mismatched lanes, using archived CPU speech.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,copyFileSync,renameSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {validateProject,validateTimeline} from '../src/core/timeline.js';
import {renderNative,runChecked} from './native-render.mjs';
const [phase,cpuDir,oldThreeDir,manifestPath]=process.argv.slice(2);
const manifest=JSON.parse(readFileSync(manifestPath,'utf8'));
const row=manifest.phases[phase];assert.ok(row);
const root=process.cwd(),cpu=resolve(cpuDir),oldThree=resolve(oldThreeDir),id=phase+'-three-polished',out=join(root,'out',id);
const actual=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();assert.equal(actual,manifest.sourceCommit);
const sha=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const read=(d,n)=>JSON.parse(readFileSync(join(d,n),'utf8'));
for(const [d,h] of [[cpu,row.cpu],[oldThree,row.three]])for(const [n,digest] of Object.entries(h))assert.equal(sha(join(d,n)),digest,'archived input mismatch '+n);
const a=validateProject(read(cpu,'scene.json')),b=validateProject(read(oldThree,'scene.json'));
assert.equal(a.id,phase+'-cpu-polished');assert.equal(b.id,id);
const expected=structuredClone(a);expected.id=id;for(const s of expected.shots){assert.equal(s.backend,'cpu');s.backend='three';}assert.deepEqual(expected,b);
const timeline=validateTimeline(b,read(cpu,'timeline.json'));assert.equal(timeline.durationFrames,row.frames);
mkdirSync(out,{recursive:true});copyFileSync(join(oldThree,'scene.json'),join(out,'scene.json'));
const names=['timeline.json','voice-report.json','kokoro-narration.wav',...(b.speech?['mix.wav','speech-report.json','captions.srt','captions.vtt']:[])];
for(const n of names)copyFileSync(join(cpu,n),join(out,n));
const audio=join(root,'public','audio',id+'.wav');mkdirSync(join(root,'public','audio'),{recursive:true});
const ff=process.env.AETHER_FFMPEG;assert.ok(ff);const cpuFilm=join(cpu,'film.mp4');
const audioHash=p=>execFileSync(ff,['-v','error','-i',p,'-map','0:a:0','-c','copy','-f','hash','-hash','sha256','-'],{encoding:'utf8'}).trim();
const cpuAudioHash=audioHash(cpuFilm);
if(b.speech)copyFileSync(join(cpu,'mix.wav'),audio);
else runChecked(root,ff,['-v','error','-y','-i',cpuFilm,'-map','0:a:0','-af','apad','-t',String(row.frames/30),'-ar','48000','-ac','1','-c:a','pcm_s16le',audio]);
const timing=renderNative({root,out,scene:b,timeline,python:'python3'});
const rendered=join(out,'film.mp4'),muxed=join(out,'shared-audio.mp4');
runChecked(root,ff,['-v','error','-y','-i',rendered,'-i',cpuFilm,'-map','0:v:0','-map','1:a:0','-c','copy','-movflags','+faststart',muxed]);
assert.equal(audioHash(muxed),cpuAudioHash);renameSync(muxed,rendered);
runChecked(root,'python3',['scripts/verify.py',out]);
for(const n of names)assert.equal(sha(join(out,n)),row.cpu[n]);
const outputs=Object.fromEntries(['scene.json','film.mp4','probe.json','render-timing.json',...names].map(n=>[n,sha(join(out,n))]));
writeFileSync(join(out,'legacy-repair-provenance.json'),JSON.stringify({version:1,phase,sourceCommit:actual,orchestrationCommit:process.env.GITHUB_SHA,originalRun:manifest.originalRun,repairRun:process.env.GITHUB_RUN_ID,originalInputs:row,sharedAacPacketHash:cpuAudioHash,audioInput:b.speech?'lossless archived CPU mix':'decoded archived CPU AAC; exact CPU AAC packets remuxed',outputs,renderSeconds:timing.renderSeconds},null,2));
